const MONTHS = ['январь', 'февраль', 'март', 'апрель', 'май', 'июнь', 'июль', 'август', 'сентябрь', 'октябрь', 'ноябрь', 'декабрь'];

const num = (v) => String(v).replace('.', ',');
function word(v) { const k = String(v).trim().toLowerCase(); return WORDS[k] || String(v).trim(); }

/** Значение для показа по-русски */
function value(key, v) {
  const s = String(v == null ? '' : v).trim(); if (!s) return '';
  switch (key) {
    case 'status': {
      if (/^актив/i.test(s)) return 'в ассортименте';
      let m = /^виведен\S*\s*(\d{4})?/i.exec(s); if (m) return 'выведен' + (m[1] ? ` в ${m[1]}` : '');
      m = /^ексклюзив\s+(.+)/i.exec(s); if (m) return 'эксклюзив ' + m[1].replace(/^Епіцентр$/i, 'Эпицентр');
      return s;
    }
    case 'format': return s.replace(/[xх×]/gi, ' × ') + ' мм';
    case 'thickness': return num(s) + ' мм';
    case 'w1': case 'wpack': case 'wpal': return num(s) + ' кг';
    case 'm2pack': case 'm2pal': return num(s);
    case 'month': { const n = Number(s); return n >= 1 && n <= 12 ? MONTHS[n - 1] : s; }
    case 'usage': case 'design': case 'purpose': return s.split(/\s*,\s*/).map(word).join(', ');
    default: return word(s);
  }
}
const label = (key, fallback) => LABELS[key] || fallback || key;

module.exports = { LABELS, value, label };
